"""Reduce: one sonnet call per researcher turns verified evidence + timeline into the cards, then a renderer
replaces [[E12]] citations with the verbatim quote, doc id and date and writes one file per format.

usage: python3 reduce.py <slug> [--render-only]"""
import json
import os
import re
import subprocess
import sys
import time

W = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.dirname(W)
RUN_DIR = "/private/tmp/claude-501/-Users-ethancai-Projects-Ongoing-AutoResearch/414d2fe3-0b7c-4161-aca0-f3ceaeffeb26/scratchpad/run"
NAMES = {"evan_hubinger": "Evan Hubinger", "samuel_bowman": "Samuel R. Bowman", "owain_evans": "Owain Evans",
         "ryan_greenblatt": "Ryan Greenblatt", "buck_shlegeris": "Buck Shlegeris", "samuel_marks": "Samuel Marks",
         "elizabeth_barnes": "Beth Barnes", "jacob_steinhardt": "Jacob Steinhardt"}
FILES = {"(a)": "a_principles.md", "(b)": "b_decision_heuristics.md", "(c)": "c_petri_transfer.md",
         "(d)": "d_extrapolation.md", "(e)": "e_taste_vector.md"}


def load_evidence(slug):
    ev = [json.loads(line) for line in open(f"{W}/evidence/{slug}.jsonl")]
    ev.sort(key=lambda e: (-int(e.get("relevance", 0)), e["date"]))
    for i, e in enumerate(ev, 1):
        e["id"] = f"E{i}"
    return ev


def call(slug, ev):
    lines = [f'{e["id"]} [{e["kind"]}|{e.get("dpoint", "")}|rel {e.get("relevance", "")}] {e["claim"]} '
             f'QUOTE: "{e["quote"]}" SOURCE: {e["title"][:80]} ({e["date"]}, {e["author_position"]} author)'
             for e in ev]
    prompt = (open(f"{W}/reduce_prompt.txt").read().replace("{NAME}", NAMES[slug])
              .replace("{EVIDENCE}", "\n".join(lines))
              .replace("{TIMELINE}", open(f"{W}/timeline/{slug}.txt").read()))
    r = subprocess.run(["claude", "-p", "--model", "sonnet", "--tools", "", "--strict-mcp-config",
                        "--no-session-persistence", "--setting-sources", "",
                        "--system-prompt", "You are a careful research-taste analyst. Output only the requested Markdown.",
                        "--output-format", "json"], input=prompt, capture_output=True, text=True, cwd=RUN_DIR)
    with open(f"{W}/calls.log", "a") as f:
        f.write(f"{time.strftime('%H:%M:%S')} reduce sonnet {slug} exit={r.returncode}\n")
    text = json.loads(r.stdout)["result"]
    open(f"{W}/reduce_raw_{slug}.md", "w").write(text)
    return text


def render(slug, text, ev):
    by_id = {e["id"]: e for e in ev}
    used = set()

    def cite(m):
        out = []
        for eid in re.findall(r"E\d+", m.group(0)):
            e = by_id.get(eid)
            if not e:
                continue
            used.add(eid)
            out.append(f'\n  > "{e["quote"].strip()}"  \n  > -- `{e["doc_id"]}` ({e["date"]}; {e["author_position"]} author)')
        return "".join(out)

    sections = re.split(r"^## ", text, flags=re.M)
    d = f"{OUT}/{slug}"
    os.makedirs(d, exist_ok=True)
    header = (f"<!-- {NAMES[slug]} taste profile. Generated by experiments/taste_petri/profiles/_work/reduce.py "
              f"from verified evidence; quotes are verbatim from data/researchers/{slug}/corpus/<doc id>.txt -->\n\n")
    for sec in sections[1:]:
        tag = sec[:3]
        body = "## " + re.sub(r"\[\[(E\d+(?:\s*[,;]\s*E\d+)*)\]\]", cite, sec)
        if tag in FILES:
            open(f"{d}/{FILES[tag]}", "w").write(header + body.strip() + "\n")
        elif tag == "(f)":
            w = json.loads(body[body.find("{"):body.rfind("}") + 1])
            principles = re.findall(r"^\d+\.\s+(.*)$", sections_by_tag(sections, "(a)"), flags=re.M)
            prof = {"researcher": slug, "weights": w, "principles": [re.sub(r"\*\*", "", p) for p in principles],
                    "sources": {"text:research": float(len(ev))},
                    "_note": "weights are LLM-estimated from text (reduce step), not fitted on choices"}
            json.dump(prof, open(f"{d}/profile.json", "w"), indent=2)
    with open(f"{d}/evidence.jsonl", "w") as f:
        for e in ev:
            f.write(json.dumps(e) + "\n")
    print(slug, "citations used:", len(used), "of", len(ev), "evidence items")


def sections_by_tag(sections, tag):
    return next((s for s in sections if s.startswith(tag)), "")


if __name__ == "__main__":
    slug = sys.argv[1]
    ev = load_evidence(slug)
    text = open(f"{W}/reduce_raw_{slug}.md").read() if "--render-only" in sys.argv else call(slug, ev)
    render(slug, text, ev)
